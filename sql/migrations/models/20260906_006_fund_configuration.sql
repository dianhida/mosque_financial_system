-- Fund-specific configuration and manually verified balance snapshots.
-- WAKAF reporting uses these tables; INFAQ remains transaction-derived.

CREATE TABLE IF NOT EXISTS public.fund_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fund_id BIGINT NOT NULL,
    setting_key VARCHAR(100) NOT NULL,
    setting_value TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_fund_settings_fund
        FOREIGN KEY (fund_id)
        REFERENCES public.funds(id)
        ON DELETE CASCADE,
    CONSTRAINT uq_fund_settings_key UNIQUE (fund_id, setting_key)
);

CREATE TABLE IF NOT EXISTS public.fund_balance_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fund_id BIGINT NOT NULL,
    balance NUMERIC(15,2) NOT NULL,
    checked_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    checked_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_fund_balance_snapshots_fund
        FOREIGN KEY (fund_id)
        REFERENCES public.funds(id)
        ON DELETE CASCADE,
    CONSTRAINT chk_fund_balance_snapshots_balance
        CHECK (balance >= 0)
);

-- Accounts are payment sources. They are not owned by a fund.
ALTER TABLE public.accounts
    DROP CONSTRAINT IF EXISTS fk_accounts_fund;
ALTER TABLE public.accounts
    DROP COLUMN IF EXISTS fund_id;
DROP INDEX IF EXISTS public.idx_accounts_fund_id;

CREATE INDEX IF NOT EXISTS idx_fund_settings_fund_id
    ON public.fund_settings(fund_id);
CREATE INDEX IF NOT EXISTS idx_fund_balance_snapshots_fund_checked_at
    ON public.fund_balance_snapshots(fund_id, checked_at DESC);

CREATE OR REPLACE FUNCTION public.set_fund_settings_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_fund_settings_set_updated_at ON public.fund_settings;
CREATE TRIGGER trg_fund_settings_set_updated_at
    BEFORE UPDATE ON public.fund_settings
    FOR EACH ROW EXECUTE FUNCTION public.set_fund_settings_updated_at();

COMMENT ON TABLE public.fund_settings IS 'Generic key/value configuration for fund-specific business rules.';
COMMENT ON COLUMN public.fund_settings.setting_key IS 'Configuration key such as target_amount or balance_source.';
COMMENT ON TABLE public.fund_balance_snapshots IS 'Historical manually verified balances; these are not ledger transactions.';
COMMENT ON COLUMN public.fund_balance_snapshots.balance IS 'Actual balance checked by an administrator at checked_at.';

-- The previous migration created v_wakaf_summary with a different column shape.
-- Drop it before creating the target/snapshot-based view.
DROP VIEW IF EXISTS public.v_wakaf_summary;

CREATE OR REPLACE VIEW public.v_wakaf_summary AS
WITH wakaf AS (
    SELECT f.id AS fund_id
    FROM public.funds f
    WHERE f.code = 'WAKAF'
), target AS (
    SELECT NULLIF(TRIM(fs.setting_value), '')::NUMERIC(15,2) AS target_amount
    FROM public.fund_settings fs
    JOIN wakaf w ON w.fund_id = fs.fund_id
    WHERE fs.setting_key = 'target_amount'
), latest_snapshot AS (
    SELECT snapshot.balance
    FROM public.fund_balance_snapshots snapshot
    JOIN wakaf w ON w.fund_id = snapshot.fund_id
    ORDER BY snapshot.checked_at DESC, snapshot.id DESC
    LIMIT 1
), expenses AS (
    SELECT COALESCE(SUM(t.amount), 0)::NUMERIC(15,2) AS total_expense
    FROM public.transactions t
    JOIN wakaf w ON w.fund_id = t.fund_id
    WHERE t.transaction_type = 'EXPENSE'
)
SELECT
    target.target_amount,
    latest_snapshot.balance AS current_balance,
    expenses.total_expense,
    CASE
        WHEN latest_snapshot.balance IS NULL THEN NULL
        ELSE (latest_snapshot.balance + expenses.total_expense)::NUMERIC(15,2)
    END AS estimated_total_collected,
    CASE
        WHEN target.target_amount IS NULL OR target.target_amount <= 0 OR latest_snapshot.balance IS NULL THEN NULL
        ELSE ROUND(((latest_snapshot.balance + expenses.total_expense) / target.target_amount) * 100, 2)
    END AS progress_percentage
FROM wakaf
LEFT JOIN target ON TRUE
LEFT JOIN latest_snapshot ON TRUE
CROSS JOIN expenses;

COMMENT ON VIEW public.v_wakaf_summary IS
    'WAKAF target and progress based on the latest manual balance snapshot plus recorded expenses.';

GRANT SELECT ON public.v_wakaf_summary TO authenticated;

